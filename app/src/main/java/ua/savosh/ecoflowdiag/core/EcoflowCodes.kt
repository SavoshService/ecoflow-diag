package ua.savosh.ecoflowdiag.core

/**
 * Пояснення кодів помилок BMS/станції. EcoFlow офіційно їх НЕ публікує — значення тут зібрані
 * за дослідами Savosh Service на реальних станціях. Тому кожне пояснення має рівень впевненості:
 * [confident] = true — підтверджено на кількох станціях; false — попередній висновок.
 *
 * errCode у цих BMS дорівнює номеру біта, що стоїть у allErrCode (напр. errCode 23 ↔ біт 23).
 */
object EcoflowCodes {

    class Doc(
        val title: String,
        /** Короткий підсумок (один рядок). */
        val short: String,
        /** Докладне пояснення для діалогу. */
        val detail: String,
        /** Серйозність: чи це справжня несправність. */
        val level: Level,
        val confident: Boolean,
    )

    /** Пояснення коду помилки BMS за його значенням (= номер біта). */
    private val BMS: Map<Long, Doc> = mapOf(
        23L to Doc(
            title = "Код 23 — заряд зупинено лімітом",
            short = "Не помилка: заряд зупинено, бо досягнуто ліміту заряду (SOC або повний заряд).",
            detail = "Це не несправність, а штатний стан. BMS виставляє цей код, коли заряд зупинено, бо станція " +
                "дійшла до ліміту заряду — вручну виставленого ліміту SOC або повних 100%. Особливо часто з'являється " +
                "в режимі UPS/байпас, коли станція тримається на 100% і живить навантаження з мережі напряму. " +
                "Якщо інших ознак проблем немає (bmsFault 0, аварійних бітів AFE немає, іконка помилки не горить) — " +
                "звертати увагу не треба.",
            level = Level.GOOD,
            confident = true,
        ),
        6L to Doc(
            title = "Код 6 — заряд зупинено через дисбаланс",
            short = "Заряд зупинено, бо одна з груп першою дійшла до межі напруги (дисбаланс).",
            detail = "З'являється в кінці заряду: одна з груп елементів дійшла до верхньої межі напруги раніше за інші, " +
                "і BMS зупинила заряд, щоб її не перезарядити. Для LFP на 100% з невеликим розкидом це часто нормально — " +
                "клітини балансуються повільно. Якщо код повторюється щоразу, а розкид груп великий (десятки мВ біля 100%), " +
                "батареї потрібне балансування: кілька повільних повних зарядів або сервісне балансування. " +
                "Апаратна перенапруга (аварійний біт AFE) при цьому НЕ спрацьовує — це програмна зупинка, не відмова.",
            level = Level.WARN,
            confident = false,
        ),
    )

    /** Пояснення за ключем коду у звіті ("bms:23", "bms:6", …). null — пояснення немає. */
    fun forKey(codeKey: String?): Doc? {
        val key = codeKey ?: return null
        val parts = key.split(":")
        if (parts.size != 2) return null
        val value = parts[1].toLongOrNull() ?: return null
        return when (parts[0]) {
            "bms" -> BMS[value] ?: unknownBms(value)
            "inv", "pd", "mppt" -> unknownOther(parts[0], value)
            else -> null
        }
    }

    /** Чи є для цього коду пояснення, яке варто показати кнопкою. */
    fun hasExplanation(codeKey: String?): Boolean = forKey(codeKey) != null

    /** Doc ЛИШЕ для задокументованого (вивченого) коду BMS; для невідомих — null. */
    fun documented(codeKey: String?): Doc? {
        val key = codeKey ?: return null
        val parts = key.split(":")
        if (parts.size != 2) return null
        val value = parts[1].toLongOrNull() ?: return null
        return if (parts[0] == "bms") BMS[value] else null
    }

    private fun unknownBms(value: Long): Doc = Doc(
        title = "Код $value — не задокументований",
        short = "EcoFlow не публікує значення кодів BMS; цей код ще не вивчено.",
        detail = "EcoFlow не публікує розшифровку кодів BMS, і саме цей код (№$value, біт $value у allErrCode) поки не " +
            "вивчено на достатній кількості станцій. Що можна зробити: подивіться інші ознаки — чи є bmsFault, аварійні " +
            "біти AFE (bqSysStatReg), чи горить іконка помилки на екрані станції. Якщо більше нічого не червоніє, найчастіше " +
            "це штатний прапорець режиму, а не поломка. Додайте власну примітку до цього коду (олівець нижче) — і коли " +
            "зрозумієте, за яких умов він з'являється, пояснення буде під рукою. Якщо станція на гарантії — спитайте код " +
            "у підтримки EcoFlow за серійним номером.",
        level = Level.WARN,
        confident = false,
    )

    private fun unknownOther(domain: String, value: Long): Doc {
        val where = when (domain) {
            "inv" -> "інвертора"
            "pd" -> "плати PD"
            "mppt" -> "MPPT (сонячного входу)"
            else -> domain
        }
        return Doc(
            title = "Код $where: $value",
            short = "Код $where не задокументований EcoFlow.",
            detail = "Станція повідомляє код $value від $where (0x${value.toString(16).uppercase()}). EcoFlow не публікує " +
                "їх розшифровку. Перевірте, чи код постійний чи зникає сам, за яких умов з'являється (навантаження, " +
                "заряд, температура), і додайте власну примітку. Якщо станція поводиться нормально — часто це минущий прапорець.",
            level = Level.WARN,
            confident = false,
        )
    }

    /** Загальна довідка «що таке коди BMS» для кнопки-підказки. */
    const val GENERAL_HELP =
        "Коди BMS — це внутрішні прапорці системи керування батареєю. EcoFlow не публікує їхню розшифровку, " +
            "тож частину значень Savosh Service вивчив на реальних станціях. Головне правило: сам по собі код у errCode " +
            "ще не означає поломку. Дивіться разом: bmsFault (постійні відмови), bqSysStatReg (апаратні аварійні біти " +
            "захисту), іконку помилки на екрані. Якщо вони чисті, а код все одно є — це майже завжди штатний прапорець режиму."
}
